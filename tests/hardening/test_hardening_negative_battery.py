    assert report.verdict == "HARDENED_EXECUTION_PASS", report.to_json()
    layer_ids = [l["layer_id"] for l in report.layers]
    assert layer_ids == ["A", "F", "G", "B", "C", "H", "H", "H", "D", "C"]
