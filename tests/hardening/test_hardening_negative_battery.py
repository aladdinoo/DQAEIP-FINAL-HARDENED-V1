    assert report3.verdict == "HARDENED_EXECUTION_FAIL"
    assert report3.details["stopped_at"] == "B"
    layer_b = [l for l in report3.layers if l["layer_id"] == "B"][0]
    assert layer_b["verdict"] == "AUTHORIZATION_REJECTED"


